def _set(d: dict, path: str, value: Any) -> None:
    if path.startswith("filters.market_cap_usd."):
        lo, hi = d["filters"]["market_cap_usd"]
        d["filters"]["market_cap_usd"] = [value, hi] if path.endswith(".min") else [lo, value]
        return
    parts = path.split(".")
    cur = d
    for p in parts[:-1]:
        cur = cur[p]
    cur[parts[-1]] = value


def _coerce(ftype: str, value: Any) -> Any:
    if value is None:
        return None
    if ftype == "number":
        if isinstance(value, bool):
            raise ValueError("expected a number")
        return float(value)
    if ftype == "integer":
        if isinstance(value, bool):
            raise ValueError("expected an integer")
        f = float(value)
        if f != int(f):
            raise ValueError("expected an integer")
        return int(f)
    if ftype == "pct_to_bps":
        # The LLM only reads percent ("3% slippage" -> 3); code converts units so the LLM never mixes up % and bps
        if isinstance(value, bool):
            raise ValueError("expected a percentage")
        bps = float(value) * 100
        if abs(bps - round(bps)) > 1e-6:
            raise ValueError("finer than 1 bps")
        return int(round(bps))
    if ftype == "boolean":
        if not isinstance(value, bool):
            raise ValueError("expected yes/no")
        return value
    if ftype == "ladder":
        if not isinstance(value, list) or not value:
            raise ValueError("take-profit ladder must be a non-empty list")
        return [{"multiple": float(s["multiple"]), "sell_pct": float(s["sell_pct"])} for s in value]
    raise ValueError(f"unknown type {ftype}")


def check_hard_rule(path: str, value: Any) -> str | None:
    """Return a rejection reason, or None if the value passes."""
    rule = HARD_RULES.get(path)
    if rule is None or value is None:
        return None
    kind, limit = rule
    shown = f"{limit / 100:g}%" if FIELD_CATALOG.get(path, {}).get("type") == "pct_to_bps" else f"{limit:g}" if isinstance(limit, (int, float)) else limit
    if kind == "max" and value > limit:
        return f"above the system limit of {shown}; limits can only be tightened, not loosened"
    if kind == "min" and value < limit:
        return f"below the system minimum of {shown}; limits can only be tightened, not loosened"
    if kind == "must" and value != limit:
        return "this is a system hard rule and cannot be turned off"
    if kind == "superset" and not set(limit).issubset(set(value)):
        return "system-forbidden extensions cannot be removed"
    return None


def cross_field_errors(d: dict) -> list[tuple[str, str]]:
    errs = []
    b, f, e = d["budget"], d["filters"], d["exit"]
    if b["total_usdc"] is not None and b["per_trade_usdc"] is not None and b["per_trade_usdc"] > b["total_usdc"]:
        errs.append(("budget.per_trade_usdc", "the per-trade cap cannot exceed the total budget"))
    dl = b.get("daily_max_loss_usdc")
    if dl is not None and b["total_usdc"] is not None and dl > b["total_usdc"]:
        errs.append(("budget.daily_max_loss_usdc", "the daily max loss cannot exceed the total budget"))
    if b["research_per_call_usdc"] > b["research_usdc"]:
        errs.append(("budget.research_per_call_usdc", "the per-call research cap cannot exceed the research budget"))
    lo, hi = f["market_cap_usd"]
    if lo >= hi:
        errs.append(("filters.market_cap_usd.max", f"the max market cap must be above the min, which is {_n(lo)} dollars now; "
                                                   f"say both, for example \"market cap between {_n(min(lo, hi) / 5)} and {_n(hi)}\""))
    lad = e["take_profit_ladder"]
    if lad:
        if sum(s["sell_pct"] for s in lad) > 100:
            errs.append(("exit.take_profit_ladder", "take-profit ladder sell percentages cannot add up to more than 100%"))
        ms = [s["multiple"] for s in lad]
        if ms != sorted(ms) or len(set(ms)) != len(ms):
            errs.append(("exit.take_profit_ladder", "take-profit multiples must strictly increase"))
    return errs


def _is_vague(quote: str) -> bool:
    q = quote.lower().replace("’", "'")
    return bool(_VAGUE_EN_RE.search(q)) or any(m in q for m in VAGUE_MARKERS_ZH)


def _norm(s: str) -> str:
    return re.sub(r"[\s，,。.!！?？、]", "", s).lower()


