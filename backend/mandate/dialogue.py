def canonical_json(obj: Any) -> str:
    return json.dumps(obj, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def compute_hash(mandate_id: str, frozen_at: str, expires_at: str, body: dict) -> str:
    payload = canonical_json({"mandate_id": mandate_id, "frozen_at": frozen_at, "expires_at": expires_at, "body": body})
    return "sha256:" + hashlib.sha256(payload.encode("utf-8")).hexdigest()


def verify_hash(m: Mandate) -> bool:
    return m.hash == compute_hash(m.mandate_id, m.frozen_at, m.expires_at, m.body.model_dump(mode="json"))


# English is the primary path ("confirm", "I confirm", "yes, confirmed", "confirm the mandate");
# Chinese "确认" stays as an extra alias.
CONFIRM_RE = re.compile(r"\bconfirm(ed|s)?\b|(?<![不没别未])确认", re.I)
NEGATE_RE = re.compile(
    r"\b(don'?t|do not|not|never|can'?t|cannot|won'?t|wouldn'?t|isn'?t|hold off|before you)\b[\w\s,']{0,20}\bconfirm"
    r"|\bunconfirm|\b(cancel|wait|hold on|hang on|change|not yet|not right|wrong|nope|scratch that)\b"
    r"|(不|没|别|未|先别|暂不)(要)?确认|取消|等一下|等等|先不|不对|改一下", re.I)


def is_confirmation(utterance: str) -> bool:
    u = utterance.replace("\u2019", "'")
    return bool(CONFIRM_RE.search(u)) and not NEGATE_RE.search(u)


def is_preset_accept(utterance: str) -> bool:
    """'no', 'looks good', 'go ahead' after 'do you want to change any of these settings?'.

    Not used as a general confirm. If the user also names a number, percent, or a field to change,
    this is not an accept (those words go to field extraction instead).
    """
    u = (utterance or "").replace("\u2019", "'")
    if not u.strip():
        return False
    if FILTERS_OK_NEGATED.search(u) and not (FILTERS_OK_RE.search(u) or PRESET_ACCEPT_RE.search(u)):
        return False
    named = bool(PCT_RE.search(normalize_utterance(u)) or amounts_in(u)
                 or re.search(r"\b(change|set|make it|raise|lower|increase|decrease|budget|cap|stop loss|take profit|fee cap)\b", u, re.I))
    if named and not re.search(r"\bno changes?\b|\bdon'?t change|\bdo not change", u, re.I):
        return False
    return bool(FILTERS_OK_RE.search(u) or PRESET_ACCEPT_RE.search(u) or GO_WORDS_RE.search(u))


# ---------------------------------------------------------------------------
# Session
# ---------------------------------------------------------------------------
@dataclass
class MandateSession:
    extractor: Extractor
    judge: ExplicitJudge
    explicit_threshold: float = EXPLICIT_THRESHOLD
    now: Callable[[], datetime] = lambda: datetime.now(timezone.utc)
    draft: dict = field(default_factory=lambda: default_body().model_dump(mode="json"))
    transcript: list[dict] = field(default_factory=list)
    frozen: Mandate | None = None
    sol_usd: SolUsd | None = None      # live SOL/USD price for dollar fee caps; None or a None result = unavailable
    filters_reviewed: bool = False     # the user accepted (or moved past) the proposed coin filters
    _recap_digest: str | None = None
    # amend mode: the session keeps running; the draft is a copy of the active mandate and becomes the next version
    base: Mandate | None = None
    versions: list = field(default_factory=list)
    spec: Any = None                   # SpecCache: extraction primed by the shadow listener (read-only cache)
    preset_offered: bool = False       # draft was filled from the saved default; 'no / looks good' may freeze it
    loosen_asked: str | None = None    # the spoken "say confirm" question already asked for the pending loosening

    @property
    def amending(self) -> bool:
        return self.base is not None

    @property
    def active(self) -> Mandate | None:
        """The mandate the session is running under (also while an amendment is being drafted)."""
        return self.frozen or self.base

    def open_amend(self) -> None:
        if self.frozen is None:
            if self.base is not None:
                return
            raise ValueError("there is no active mandate to amend yet")
        self.base, self.frozen = self.frozen, None
        self.draft = self.base.body.model_dump(mode="json")
        self.filters_reviewed = True
        self._recap_digest = None

    def cancel_amend(self) -> None:
        if self.base is not None:
            self.frozen, self.base = self.base, None
            self._recap_digest = None

    def apply_preset(self, body: dict) -> None:
        """Load the saved default mandate into the draft (first-time setup skip). Not frozen yet."""
        if self.frozen is not None or self.base is not None:
            raise MandateFrozenError("the mandate is frozen and read-only")
        self.draft = default_body().model_dump(mode="json")
        # body is already a complete, validated dump
        self.draft = body
        self.filters_reviewed = True
        self.preset_offered = True
        self._recap_digest = None
        self.transcript.append({"preset": True})

    def amend_changes(self) -> list[str]:
        if self.base is None:
            return []
        return _diff_paths(self.base.body.model_dump(mode="json"), self.draft)

    def amend_direction(self) -> str:
        """'loosen' if any of the user's own limits goes up (or is removed): that needs a spoken, explicit "confirm".
        'tighten' if every change lowers one of those limits: it applies right away. Otherwise 'other' (normal flow)."""
        ch = self.amend_changes()
        if not ch:
            return "other"
        old = self.base.body.model_dump(mode="json")
        moves = []
        for path in ch:
            if path not in LIMIT_PATHS:
                moves.append("other")
                continue
            a, b = _get(old, path), _get(self.draft, path)
            if b is None:
                moves.append("loosen" if a is not None else "other")
            elif a is None or b < a:
                moves.append("tighten")
            else:
                moves.append("loosen")
        if "loosen" in moves:
            return "loosen"
        return "tighten" if all(m == "tighten" for m in moves) else "other"

    def limit_moves(self) -> list[tuple[str, Any, Any]]:
        """(label, old, new) for each changed user limit, for the spoken question / acknowledgement."""
        if self.base is None:
            return []
        old = self.base.body.model_dump(mode="json")
        return [(LIMIT_PATHS[p], _get(old, p), _get(self.draft, p)) for p in self.amend_changes() if p in LIMIT_PATHS]

    def apply_tightening(self, utterance: str) -> Mandate:
        """Lowering the user's own limits is the safe direction: it applies at once, no confirm word needed."""
        if self.base is None or self.amend_direction() != "tighten":
            raise ValueError("only a change that lowers limits applies without confirm")
        m = self._freeze(MandateBody.model_validate(self.draft))
        self.transcript.append({"amend": utterance, "kind": "tighten", "changes": self.amend_changes()})
        self.base = None
        return m

    def amend_kind(self) -> str:
        ch = self.amend_changes()
        if not ch:
            return "none"
        return "filters" if all(p.startswith("filters.") for p in ch) else "guards"

    def stage(self) -> str:
        if self.base is not None:
            return "amend"
        if any(_get(self.draft, p) is None for p in FUNDS_FIELDS):
            return "funds"
        if not self.filters_reviewed:
            return "filters"
        return "exits" if self.missing_required() else "ready"

    # ---- extraction (user's raw words only) ----
    def _extract_prompt(self, utterance: str, question: str) -> tuple[str, str]:
        catalog = "\n".join(f"- {p}: {m['label']}, {m['type']}" + (f" ({m['hint']})" if m.get("hint") else "")
                            for p, m in FIELD_CATALOG.items())
        return EXTRACT_SYSTEM.format(catalog=catalog), f"The system just asked the user: {question}\nUser's exact words: {utterance}"

    def prime_extract(self, utterance: str) -> bool:
        """Shadow listener: start the extraction for words the user just finished saying, with the question submit()
        will use (a running session is amended, so its question is the amend one). Read-only; nothing changes here."""
        if self.spec is None or not utterance.strip():
            return False
        question = STAGE_QUESTIONS["amend"] if (self.frozen is not None or self.base is not None) else self.question()
        system, user = self._extract_prompt(utterance, question)
        return self.spec.prime(system, user, self.extractor)

    async def extract_fields(self, utterance: str, round_no: int) -> dict:
        system, user = self._extract_prompt(utterance, self.question())
        out = await self.spec.take(system, user) if self.spec is not None else None
        if out is None:
            out = await self.extractor(system, user)
        if not isinstance(out, dict):
            return {"fields": [], "other_requests": []}
        return {"fields": out.get("fields") or [], "other_requests": out.get("other_requests") or []}

    def question(self) -> str:
        return STAGE_QUESTIONS[self.stage()]

    def _ensure_open(self) -> None:
        if self.frozen is not None:
            raise MandateFrozenError("the mandate is frozen and read-only")

    async def submit(self, utterance: str, round_no: int = 1) -> TurnResult:
        self._ensure_open()
        self.transcript.append({"round": round_no, "utterance": utterance})
        stage_before = self.stage()
        question = self.question()
        raw = await self.extract_fields(utterance, round_no)
        judge_as: dict[int, tuple[str, Any]] = {}   # what JEV sees, when it differs from the stored value (USD fee)
        outcomes: list[FieldOutcome] = []
        candidates: list[FieldOutcome] = []
        norm_utt = _norm(utterance)

        proceed = False
        for req in raw["other_requests"]:
            if _is_proceed(str(req.get("quote", "") or "")) or _is_proceed(str(req.get("description", "") or "")) \
                    or _is_new_round(str(req.get("quote", "") or "")) or _is_new_round(str(req.get("description", "") or "")):
                proceed = True          # "start researching" means continue, not a hard-rule change
                continue
            outcomes.append(FieldOutcome(path="system", label=str(req.get("description", "")), status="rejected",
                                         quote=str(req.get("quote", "")), reason="this is a system hard rule and cannot be changed through the mandate"))

        items = [dict(x) for x in raw["fields"] if isinstance(x, dict)]
        if not items and not outcomes and not proceed:
            items = self._bare_answer(utterance, stage_before)
        items = self._apply_both_exits(items, utterance, stage_before)
        items = self._fix_items(items, utterance, stage_before)
        items = self._apply_both_exits(items, utterance, stage_before)
        seen: set[str] = set()
        for item in items:
            path = str(item.get("path", ""))
            quote = str(item.get("quote", "") or "")
            root = path.split(".")[0]
            if path not in FIELD_CATALOG:
                reason = "this is a system hard rule and cannot be changed through the mandate" if (root in SYSTEM_ONLY_KEYS or path in SYSTEM_ONLY_KEYS or root == "funding") else "unknown field"
                outcomes.append(FieldOutcome(path=path, label=path, status="rejected", quote=quote, reason=reason))
                continue
            if path in seen:
                continue
            seen.add(path)
            meta = FIELD_CATALOG[path]
            o = FieldOutcome(path=path, label=meta["label"], status="unclear", quote=quote)
            # 1. the quote must appear verbatim in the utterance
            if not quote or _norm(quote) not in norm_utt:
                o.reason = "could not find those words in what you said"
                outcomes.append(o)
                continue
            # 2. type
            try:
                o.value = _coerce(meta["type"], item.get("value"))
            except (ValueError, TypeError, KeyError) as e:
                o.reason = f"could not read the value: {e}"
                outcomes.append(o)
                continue
            if o.value is None:
                if path == FEE_PATH and re.search(r"\bdefault\b", quote, re.I):   # "fees: use the default" is explicit
                    o.status, o.value, o.said = "accepted", DEFAULT_MAX_FEE_SOL, "the default"
                    outcomes.append(o)
                    continue
                o.reason = "no definite value was given"
                outcomes.append(o)
                continue
            # 3. deterministic vague words
            if _is_vague(quote) or _quote_window_vague(utterance, quote):
                o.reason = "too vague (hedge word detected)"
                outcomes.append(o)
                continue
            # 3b. fee cap given in dollars/cents: code converts with a live SOL price, never a guess
            if path == FEE_PATH and _fee_currency(utterance, quote) == "usd":
                usd = _fee_usd(utterance, quote, o.value)
                price = await self._sol_price()
                o.said = _say_usd(usd)
                if price is None:
                    o.reason = (f"I couldn't get a live SOL price to convert {o.said} to SOL; say a SOL amount, "
                                f"or leave it out to keep the default {DEFAULT_MAX_FEE_SOL:g} SOL")
                    outcomes.append(o)
                    continue
                judge_as[id(o)] = ("max fee per trade (USD)", usd)
                o.value = round(usd / price, 6)
                o.said = f"{o.said} (about {o.value:g} SOL at ${price:,.2f} per SOL)"
            # 4. hard rules
            hr = check_hard_rule(path, o.value if meta["type"] != "ladder" else None)
            if hr:
                o.status, o.reason = "rejected", (f"{o.said} is {hr}" if o.said else hr)
                outcomes.append(o)
                continue
            if item.get("_judge"):
                judge_as[id(o)] = item["_judge"]
            if item.get("_said"):
                o.said = item["_said"]
            if item.get("_bare"):
                o.status, o.p_explicit = "accepted", 1.0   # a lone definite number: no judge needed
                outcomes.append(o)
                continue
            candidates.append(o)

        # 5. JEV explicitness (concurrent); can only downgrade accepted to unclear
        probs = await asyncio.gather(*[self.judge.explicit(question, utterance, *judge_as.get(id(c), (c.label, c.value)))
                                       for c in candidates], return_exceptions=True)
        for c, p in zip(candidates, probs):
            if isinstance(p, BaseException):
                c.reason = "explicitness check failed; treated as vague"
            else:
                c.p_explicit = float(p)
                if c.p_explicit >= self.explicit_threshold:
                    c.status = "accepted"
                else:
                    c.reason = f"not explicit enough (P={c.p_explicit:.2f})"
            outcomes.append(c)

        # 6. apply accepted fields one by one; roll a field back if pydantic / cross-field checks fail
        for o in [o for o in outcomes if o.status == "accepted"]:
            if o.value is None:
                continue  # never clear a field the user did not give a definite value for
            trial = copy.deepcopy(self.draft)
            _set(trial, o.path, o.value)
            err = self._validate(trial, o.path)
            if err:
                o.status, o.reason = "rejected", err
            else:
                self.draft = trial
        # 7. fee cap omitted -> code applies the default (never over a rejected / unclear fee attempt in this turn)
        fee_default = False
        if not self.amending and _get(self.draft, FEE_PATH) is None and not any(o.path == FEE_PATH for o in outcomes):
            _set(self.draft, FEE_PATH, DEFAULT_MAX_FEE_SOL)
            fee_default = True
        # 8. coin-filter review: a clear "looks good" (with nothing rejected / unclear), or jumping ahead to exits
        if stage_before != "funds" and not self.filters_reviewed:
            blocked = any(o.status != "accepted" and not FILTERS_OK_RE.search(o.quote or "") for o in outcomes)
            accepted_ok = (bool(FILTERS_OK_RE.search(utterance)) and not FILTERS_OK_NEGATED.search(utterance) or proceed) and not blocked
            jumped = any(o.status == "accepted" and o.path in EXIT_FIELDS for o in outcomes)
            if accepted_ok or jumped:
                self.filters_reviewed = True
        elif stage_before == "funds" and any(o.status == "accepted" and o.path in EXIT_FIELDS for o in outcomes) \
                and self.stage() != "funds":
            self.filters_reviewed = True   # everything in one breath: filters stay at the current draft
        self._recap_digest = None  # draft changed, old recap is void
        missing = self.missing_required()
        st = self.stage()
        if not proceed and _is_new_round(utterance):
            proceed = True
        speak = self._speak(outcomes, missing, stage_before, st, fee_default, proceed)
        return TurnResult(utterance, outcomes, missing, speak, raw, st, fee_default, proceed,
                          self.amend_kind() if self.amending else None)

    # ---- deterministic help for spoken answers (only ever uses the user's own words) ----
    def _bare_answer(self, utterance: str, stage: str) -> list[dict]:
        """The extractor found nothing, but the user gave one bare value to the question just asked
        ("30%" when only take profit is missing, "five cents" when only the total is missing)."""
        both = _both_exit_items(utterance)
        if both and stage in ("exits", "filters", "amend", "ready"):
            return both
        nu = normalize_utterance(utterance)
        if stage == "funds":
            missing = [p for p in BUDGET_FIELDS if _get(self.draft, p) is None]
            amts = amounts_in(utterance)
            if len(missing) == 1 and len(amts) == 1 and not PCT_RE.search(nu):
                return [{"path": missing[0], "value": amts[0], "quote": utterance}]
        if stage in ("exits", "filters"):
            missing = [p for p in EXIT_FIELDS if _get(self.draft, p) in (None, [], ())]
            nums = re.findall(r"(?<![\w.])(\d+(?:\.\d+)?)(?![\w.])", nu)
            if len(missing) == 1 and len(nums) == 1 and (stage == "exits" or PCT_RE.search(nu)):
                v = float(nums[0])
                return [{"path": missing[0], "value": v if missing[0] == SL_PATH else v, "quote": utterance}]
        return []

    def _apply_both_exits(self, items: list[dict], utterance: str, stage: str) -> list[dict]:
        """'both of them 1.5%' after an SL/TP question sets both exits. Drop budget fields the
        extractor may have invented; never clear already-set funds."""
        both = _both_exit_items(utterance)
        if not both:
            return items
        # A percent-only "both" answer is not a budget change.
        if stage in ("exits", "filters", "amend", "ready") or not any(_get(self.draft, p) is None for p in BUDGET_FIELDS):
            items = [it for it in items if str(it.get("path", "")) not in BUDGET_FIELDS]
        have = {str(it.get("path", "")) for it in items}
        for it in both:
            if it["path"] not in have:
                items.append(it)
                have.add(it["path"])
        return items

    def _fix_items(self, items: list[dict], utterance: str, stage: str) -> list[dict]:
        """Fix common extractor slips using the user's words: cents in budget fields, a take-profit percent that landed
        in stop loss (or a bare number that overwrote stop loss), and percent take-profits given as numbers."""
        claimed = {str(x.get("path", "")) for x in items}
        out = []
        for it in items:
            path, quote, v = str(it.get("path", "")), str(it.get("quote", "") or ""), it.get("value")
            if path == FEE_PATH and stage == "funds" and not FEE_WORDS_RE.search(utterance):
                # "let's just say five cents" while only the total is missing answers the budget, not the fee cap
                missing = [p for p in BUDGET_FIELDS if _get(self.draft, p) is None and p not in claimed]
                amts = amounts_in(utterance)
                if len(missing) == 1 and len(amts) == 1:
                    claimed.discard(path)
                    path = missing[0]
                    claimed.add(path)
                    it["path"], it["value"], v = path, amts[0], amts[0]
                    it["quote"] = quote = quote or utterance
            if path in BUDGET_FIELDS and quote:
                ctx = quote + " " + _after(utterance, quote)
                if FEE_CENTS_RE.search(ctx) and not DOLLAR_RE.search(ctx):
                    amts = amounts_in(ctx)
                    if len(amts) == 1 and not (isinstance(v, (int, float)) and abs(float(v) - amts[0]) < 1e-9):
                        it["value"] = amts[0]
            if path in EXIT_FIELDS and quote:
                kind = _exit_kind(utterance, quote)
                sl_set = _get(self.draft, SL_PATH) is not None
                tp_set = _get(self.draft, TP_PATH) not in (None, [], ())
                new = path
                if kind == "tp":
                    new = TP_PATH
                elif kind == "sl":
                    new = SL_PATH
                elif path == SL_PATH and sl_set and not tp_set and TP_PATH not in claimed:
                    new = TP_PATH          # bare "30%" after stop loss is set answers take profit; never overwrite stop loss
                elif stage == "exits" and (sl_set != tp_set):
                    new = SL_PATH if not sl_set else TP_PATH
                if new != path:
                    if new == SL_PATH and isinstance(v, list) and len(v) == 1 and isinstance(v[0], dict):
                        v = v[0].get("multiple")
                        v = (v - 1) * 100 if isinstance(v, (int, float)) and 1 < v < 2 else v
                    claimed.discard(path)
                    claimed.add(new)
                    path = new
                    it["path"] = new
                    it["value"] = v
                if path == TP_PATH:
                    it.update(_tp_from_words(utterance, quote, it.get("value")))
            group = BUDGET_FIELDS if path in BUDGET_FIELDS else EXIT_FIELDS if path in EXIT_FIELDS else ()
            gap = [p for p in group if _get(self.draft, p) in (None, [], ())]
            if len(items) == 1 and gap == [path] and _is_bare_number(utterance):
                it["_bare"] = True     # code-verified: one definite number answering the question just asked
            out.append(it)
        return out

    async def _sol_price(self) -> float | None:
        if self.sol_usd is None:
            return None
        try:
            p = await self.sol_usd()
        except Exception:  # noqa: BLE001
            return None
        return float(p) if isinstance(p, (int, float)) and not isinstance(p, bool) and p > 0 else None

    def _validate(self, d: dict, path: str) -> str | None:
        try:
            MandateBody.model_validate(d)
        except ValidationError as e:
            return "invalid value: " + "; ".join(err["msg"] for err in e.errors()[:2])
        # the draft was valid before this change, so any new cross-field error is caused by this change
        errs = cross_field_errors(d)
        return errs[0][1] if errs else None

    def missing_required(self) -> list[str]:
        return [p for p in REQUIRED_FIELDS if _get(self.draft, p) is None]   # [] take-profit ladder = "no automatic take profit" (saved default)

    def _speak(self, outcomes: list[FieldOutcome], missing: list[str], before: str = "funds", stage: str | None = None,
               fee_default: bool = False, proceed: bool = False) -> str:
        """Short, casual lines; the full settings live on screen. Exact numbers only."""
        stage = stage or self.stage()
        parts = []
        acc = [o for o in outcomes if o.status == "accepted"]
        said = [_say(o) for o in acc] + ([f"fee cap set to the default {DEFAULT_MAX_FEE_SOL:g} SOL"] if fee_default else [])
        if said:
            parts.append("Got it: " + ", ".join(said) + ".")
        for o in outcomes:
            if o.status == "unclear":
                if o.path == FEE_PATH:
                    parts.append(o.reason[:1].upper() + o.reason[1:] + "." if "SOL price" in o.reason else
                                 f"I didn't get a clear fee cap; say a SOL or dollar amount, or leave it out to keep the default {DEFAULT_MAX_FEE_SOL:g} SOL.")
                else:
                    parts.append(f"I didn't get a clear value for {_short(o.label)}; please give a specific number.")
            elif o.status == "rejected":
                parts.append(f"{_short(o.label)[:1].upper() + _short(o.label)[1:]} can't be set that way: {o.reason}.")
        if stage == "amend":
            parts.append(self._amend_hint(proceed, bool([o for o in outcomes if o.status != "accepted"])))
            return " ".join(parts)
        if stage == "funds":
            need = [_short(FIELD_CATALOG[p]["label"]) for p in FUNDS_FIELDS if p in missing]
            parts.append("I still need your " + " and ".join(need) + ".")
        elif stage == "filters":
            if before == "funds":
                parts.append("My proposed coin filters are on the right; change any of them, "
                             "or say \"looks good\" and we'll set stop loss and take profit.")
            else:
                parts.append("Anything else to change, or does it look good?")
        elif stage == "exits":
            if before in ("funds", "filters"):
                parts.append("Great, keeping these filters. What stop loss and take profit do you want?")
            else:
                need = [_short(FIELD_CATALOG[p]["label"]) for p in missing]
                parts.append("I still need your " + " and ".join(need) + ".")
        else:  # ready
            parts.append("The full settings are on the right; if they look right, say \"confirm\".")
        return " ".join(parts)

    def _amend_hint(self, proceed: bool, problems: bool) -> str:
        kind = self.amend_kind()
        if kind == "guards":
            names = sorted({_short(FIELD_CATALOG[p]["label"]) if p in FIELD_CATALOG else p for p in self.amend_changes()
                            if not p.startswith("filters.")})
            return (f"That changes a guard rule ({', '.join(names)}). Say \"confirm\" to apply it and start a new research round; "
                    "open positions keep the stop loss and take profit they were bought with.")
        if kind == "filters":
            return ("Say \"start research\" to run a new round with these filters." if (problems or not proceed)
                    else "Starting a new research round with these filters.")
        if problems:
            return "Nothing changed yet."
        return ("Starting a new research round with the same settings." if proceed else
                "Nothing changed yet. Tell me what to change, or say \"start research\" for a new round with the same settings.")

    def apply_amend(self, utterance: str, recap_digest: str | None = None) -> Mandate:
        """Make the amended draft the next mandate version. A guard change needs a clear "confirm" and the latest recap;
        a filter-only change (or none) may also go with "start research" / "yes, go"."""
        if self.base is None:
            raise ValueError("there is no amendment in progress")
        kind = self.amend_kind()
        u = utterance or ""
        if kind == "guards":
            if not is_confirmation(u):
                raise ValueError("a guard change needs a clear \"confirm\"")
            current = hashlib.sha256(canonical_json(self.draft).encode()).hexdigest()[:16]
            if recap_digest != current:
                raise ValueError("the recap is stale; recap again first")
        else:
            ok = is_confirmation(u) or ((_is_new_round(u) or _is_proceed(u) or GO_WORDS_RE.search(u)) and not NEW_ROUND_NEGATED.search(u))
            if not ok:
                raise ValueError("did not hear \"start research\" or \"confirm\"")
        if kind == "none":
            m = self.base
            self.frozen, self.base = m, None
            return m
        m = self._freeze(MandateBody.model_validate(self.draft))
        self.transcript.append({"amend": utterance, "kind": kind, "changes": self.amend_changes()})
        self.base = None
        return m

    def _freeze(self, body: MandateBody) -> Mandate:
        now = self.now().replace(microsecond=0)
        frozen_at = now.isoformat().replace("+00:00", "Z")
        expires_at = (now + timedelta(hours=body.expires_in_hours)).isoformat().replace("+00:00", "Z")
        mandate_id = f"m_{now:%Y%m%d}_{secrets.token_hex(3)}"
        h = compute_hash(mandate_id, frozen_at, expires_at, body.model_dump(mode="json"))
        self.frozen = Mandate(mandate_id=mandate_id, frozen_at=frozen_at, expires_at=expires_at, body=body, hash=h)
        self.versions.append(self.frozen)
        return self.frozen

    # ---- recap and freeze ----
    def recap(self) -> dict:
        """Return the recap text and its digest; a confirmation must match the latest recap."""
        self._ensure_open()
        missing = self.missing_required()
        if missing:
            return {"ready": False, "missing_required": missing, "text": None, "digest": None}
        text = recap_text(self.draft)
        self._recap_digest = hashlib.sha256(canonical_json(self.draft).encode()).hexdigest()[:16]
        return {"ready": True, "missing_required": [], "text": text, "digest": self._recap_digest}

    def confirm(self, utterance: str, recap_digest: str) -> Mandate:
        self._ensure_open()
        if self.missing_required():
            raise ValueError("required fields are missing; cannot freeze")
        current = hashlib.sha256(canonical_json(self.draft).encode()).hexdigest()[:16]
        if self._recap_digest is None or recap_digest != self._recap_digest or recap_digest != current:
            raise ValueError("the recap is stale; recap again first")
        if not is_confirmation(utterance):
            if not (self.preset_offered and is_preset_accept(utterance)):
                raise ValueError("did not hear a clear \"confirm\"")
        m = self._freeze(MandateBody.model_validate(self.draft))
        self.transcript.append({"confirm": utterance})
        return m


def _short(label: str) -> str:
    """'stop loss (%)' -> 'stop loss'."""
    return re.sub(r"\s*\([^)]*\)$", "", label)


def _say(o: FieldOutcome) -> str:
    """Spoken form of an accepted field: 'stop loss 30%', 'take-profit at 2x sell 50%'. Exact numbers only."""
    name = _short(o.label)
    if o.path == "budget.total_usdc" and not o.said:
        return f"{_money(o.value)} total"
    if o.path == "budget.per_trade_usdc" and not o.said:
        return f"at most {_money(o.value)} per trade"
    if o.said and o.path == TP_PATH:
        return f"take profit {o.said}"
    if o.said:
        return f"{name} {o.said}" if o.path != FEE_PATH or o.said != "the default" else f"{name} the default {DEFAULT_MAX_FEE_SOL:g} SOL"
    ftype = FIELD_CATALOG[o.path]["type"]
    unit = (re.search(r"\(([^)]*)\)$", o.label) or [None, ""])[1]
    v = o.value
    if ftype == "ladder":
        return "take-profit " + _ladder_text(v)
    if ftype == "boolean":
        return f"{name} {'on' if v else 'off'}"
    if ftype == "pct_to_bps":
        return f"{name} {_n(v / 100)}%"
    num = _n(v)
    if unit == "%":
        return f"{name} {num}%"
    if unit in ("USDC", "USD"):
        return f"{name} {_usd(v)}" if v >= 1000 else f"{name} {num} dollars"
    return f"{name} {num} {unit}".rstrip()


def _is_bare_number(utterance: str) -> bool:
    nu = normalize_utterance(utterance).lower()
    nu = _FILLERS_RE.sub(" ", nu)
    nu = re.sub(r"[\s,.!?]+", " ", nu).strip()
    return bool(BARE_NUMBER_RE.match(nu))


def _is_new_round(text: str) -> bool:
    t = (text or "").strip()
    return bool(t) and bool(NEW_ROUND_RE.search(t)) and not NEW_ROUND_NEGATED.search(t)


def _diff_paths(a: Any, b: Any, prefix: str = "") -> list[str]:
    """Dotted paths whose values differ (lists / tuples compared whole)."""
    if isinstance(a, dict) and isinstance(b, dict):
        out = []
        for k in sorted(set(a) | set(b)):
            out += _diff_paths(a.get(k), b.get(k), f"{prefix}{k}.")
        return out
    if json.dumps(_numnorm(a), sort_keys=True, default=str) != json.dumps(_numnorm(b), sort_keys=True, default=str):
        return [prefix.rstrip(".")]
    return []


def _numnorm(x: Any) -> Any:
    if isinstance(x, bool) or x is None or isinstance(x, str):
        return x
    if isinstance(x, (int, float)):
        return float(x)
    if isinstance(x, dict):
        return {k: _numnorm(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_numnorm(v) for v in x]
    return x


def _is_proceed(text: str) -> bool:
    return bool(text.strip()) and bool(PROCEED_RE.search(text.strip()))


def _before(utterance: str, quote: str, n: int = 2) -> str:
    i = utterance.find(quote)
    return " ".join(re.findall(r"[\w'$.¢%-]+", utterance[:i])[-n:]) if i > 0 else ""


def _both_exit_items(utterance: str) -> list[dict]:
    """If the user said 'both (of them) 1.5%' / 'both 1.5 percent', return SL + TP items.

    Take profit +1.5% is a ladder multiple of 1.015, sell 100%. Does not change vague-marker or cent rules.
    """
    if not utterance or not BOTH_EXITS_RE.search(utterance):
        return []
    nu = normalize_utterance(utterance)
    found = list(PCT_RE.finditer(nu))
    if len(found) != 1:
        return []
    # a dollar amount in the same sentence is not a pure exit "both"
    if amounts_in(utterance) and DOLLAR_RE.search(utterance) and not PCT_RE.search(utterance):
        return []
    pct = float(found[0][1])
    if pct <= 0:
        return []
    quote = found[0].group(0)
    tp = _tp_from_words(utterance, quote, pct)
    if not tp.get("value"):
        tp = {"value": [{"multiple": round(1 + pct / 100, 6), "sell_pct": 100.0}],
              "_judge": ("take profit (percent gain over the buy price)", pct),
              "_said": "at +" + _n(pct) + "% sell 100%"}
    tp.setdefault("quote", quote)
    return [{"path": SL_PATH, "value": pct, "quote": quote},
            {"path": TP_PATH, "quote": quote, **tp}]


def _exit_kind(utterance: str, quote: str) -> str | None:
    """'tp' / 'sl' from the user's own words: the quote first, then 2 words after, then 2 words before."""
    for ctx in (quote, _after(utterance, quote), _before(utterance, quote)):
        tp, sl = bool(TP_WORDS_RE.search(ctx)), bool(SL_WORDS_RE.search(ctx))
        if tp != sl:
            return "tp" if tp else "sl"
        if tp and sl:
            return None
    return None


def _sell_pct_in(ctx: str) -> float | None:
    m = re.search(r"\bsell(?:ing)?\s+(half|all|everything|it all|the whole|a third|a quarter|(\d+(?:\.\d+)?)\s*(?:%|percent))", ctx, re.I)
    if not m:
        return None
    w = m[1].lower()
    return {"half": 50.0, "a third": 33.0, "a quarter": 25.0}.get(w, 100.0) if not m[2] else float(m[2])


def _tp_from_words(utterance: str, quote: str, value: Any) -> dict:
    """'take profit 30%' -> [{multiple 1.3, sell_pct 100}] unless the user said how much to sell. 'sell half at 2x' is untouched."""
    ctx = normalize_utterance(quote + " " + _after(utterance, quote, 3))
    if TP_MULTIPLE_RE.search(ctx):
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            return {"value": [{"multiple": float(value), "sell_pct": _sell_pct_in(ctx) or 100.0}]}
        return {}
    pm = PCT_RE.search(ctx)
    pct = float(pm[1]) if pm else None
    if isinstance(value, dict):
        value = [value]
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        pct = pct if pct is not None else float(value)      # the user's "30%" wins over whatever number the extractor gave
    elif isinstance(value, list) and len(value) == 1 and isinstance(value[0], dict) and pct is not None:
        m = value[0].get("multiple")
        if not (isinstance(m, (int, float)) and (abs(m - pct) < 1e-9 or abs(m - pct / 100) < 1e-9
                                                 or abs(m - (1 + pct / 100)) < 1e-9 or m <= 1)):
            return {}
    else:
        return {}
    if pct is None or pct <= 0:
        return {}
    sell = _sell_pct_in(ctx)
    if sell is None:
        rest = PCT_RE.sub(" ", ctx, count=1)
        sell = _sell_pct_in(rest)
    sell = sell or 100.0
    return {"value": [{"multiple": round(1 + pct / 100, 6), "sell_pct": sell}],
            "_judge": ("take profit (percent gain over the buy price)", pct),
            "_said": f"at +{_n(pct)}% sell {_n(sell)}%"}


def _ladder_text(lad) -> str:
    out = []
    for st in lad or []:
        m, sp = st["multiple"], st["sell_pct"]
        out.append(f"at {_n(m)}x sell {_n(sp)}%" if abs(m - round(m)) < 1e-9 else f"at +{_n(round((m - 1) * 100, 6))}% sell {_n(sp)}%")
    return "; ".join(out)


def _after(utterance: str, quote: str, n: int = 2) -> str:
    i = utterance.find(quote)
    return " ".join(re.findall(r"[\w'$.¢-]+", utterance[i + len(quote):])[:n]) if i >= 0 else ""


def _fee_currency(utterance: str, quote: str) -> str:
    """'usd' if the fee was said in dollars/cents, else 'sol' (the field's own unit, as before)."""
    if FEE_SOL_RE.search(quote):
        return "sol"
    after = _after(utterance, quote)
    if FEE_USD_RE.search(quote):
        return "usd"
    if FEE_SOL_RE.search(after):
        return "sol"
    return "usd" if FEE_USD_RE.search(after) else "sol"


def _fee_usd(utterance: str, quote: str, value: float) -> float:
    """The extractor is told to give dollars ("20 cents" -> 0.2). If it copied the cent number instead (20), fix it here."""
    ctx = quote + " " + _after(utterance, quote)
    if FEE_CENTS_RE.search(ctx) and not re.search(r"\$|\bdollars?\b|\bbucks?\b", ctx, re.I):
        nums = [float(x) for x in re.findall(r"\d+(?:\.\d+)?", quote)]
        if any(abs(value - n) < 1e-9 for n in nums):
            return value / 100
    return value


def _say_usd(usd: float) -> str:
    c = round(usd * 100)
    if usd < 1 and abs(usd * 100 - c) < 1e-9:
        return "1 cent" if c == 1 else f"{c:g} cents"
    return f"{_n(usd)} dollars"


def _money(usd: float) -> str:
    return _say_usd(usd) if usd < 1 else f"{_n(usd)} dollars"


def _quote_window_vague(utterance: str, quote: str) -> bool:
    """A hedge right next to the quote also counts as vague: up to 3 words on each side for English
    ("around 50 dollars", "10 or so"), or 3 characters for Chinese ("50 左右", "大概 10 块")."""
    i = utterance.find(quote)
    if i < 0:
        return False
    before, after = utterance[:i], utterance[i + len(quote):]
    words = lambda t: re.findall(r"[\w'~$%.-]+", t)  # noqa: E731
    en_window = " ".join(words(before)[-3:] + [quote] + words(after)[:3])
    zh_window = utterance[max(0, i - 3): i + len(quote) + 3]
    return _is_vague(en_window) or _is_vague(zh_window)
